"""Codex ``fileChange`` approvals check every path they write (connector 0.9.6).

Failure cases written before the implementation:
- F1: a change whose source ``path`` is inside the scope but whose ``kind.move_path``
  target is outside (absolute, or relative ``..``) is auto-approved;
- F2: a move whose source is outside but target inside, or an item whose second change
  moves out, is auto-approved;
- F3: a change with a structural error in the fields the check reads (``path`` empty,
  not a string or missing; ``kind`` missing, not an object, or with a ``type`` that is
  not exactly ``add``/``delete``/``update``, such as a list; a non-null ``move_path``
  that is empty, not a string or on ``add``/``delete`` (absent or null means no
  target); ``changes`` empty, not a list or holding a non-object) is auto-approved or
  makes handling that message fail, so the approval is neither answered nor reported.
  This is not a full ``FileUpdateChange`` validation (``diff`` is not checked);
- F4: a path the OS cannot resolve (an unknown user's ``~user``, a NUL byte) in
  ``path``, ``move_path`` or ``grantRoot`` is auto-approved or loses the approval;
- F5: a ``grantRoot`` outside the scope is auto-approved (checked before 0.9.6 too);
- F6: legal changes (``update`` with ``move_path`` absent or null, moves inside the
  scope, ``add``, ``delete``, a relative path inside the cwd, a ``grantRoot`` absent,
  null or inside) stop being auto-approved, or a malformed one disturbs later ones.

Not covered here (outside this fix): an unhashable item ``id``, and a non-null
``grantRoot`` that is empty or not a string (absent or null skips the check).

Well-formed messages are validated against the schema generated by
``codex app-server generate-json-schema`` from codex-cli 0.169.0 (``fakes/codex_schema``);
deliberately malformed ones skip that validation.
"""

from __future__ import annotations

import asyncio
import json
import time
from pathlib import Path
from typing import Any

import jsonschema
import pytest
import test_codex_phase2 as codex
from websockets.asyncio.server import serve

SCHEMA = Path(__file__).parent / "fakes" / "codex_schema"
UNKNOWN_HOME = "~yuki-no-such-user-0x7f/x.py"


def valid(name: str, value: Any) -> Any:
    jsonschema.validate(value, json.loads((SCHEMA / f"{name}.json").read_text()))
    return value


def started_item(item: Any, changes: Any) -> dict[str, Any]:
    return {
        "threadId": "thread",
        "turnId": "turn-1",
        "startedAtMs": int(time.time() * 1000),
        "item": {"id": item, "type": "fileChange", "status": "inProgress", "changes": changes},
    }


async def outcome(owner: codex.AppServer, events: Any, identity: int) -> str:
    """What became of one native request: answered by the connector or reported."""
    answered = asyncio.ensure_future(owner.answers.get())
    reported = asyncio.ensure_future(codex.until(events, lambda kind, value: kind == "permission"))
    done, pending = await asyncio.wait(
        {answered, reported}, timeout=3, return_when=asyncio.FIRST_COMPLETED
    )
    for task in pending:
        task.cancel()
    await asyncio.gather(*pending, return_exceptions=True)
    if not done:
        return "neither answered nor reported"
    if answered in done:
        answer = answered.result()
        assert answer["id"] == identity
        return f"connector:{answer['result'].get('decision')}"
    _kind, report = reported.result()
    assert report["payload"]["native_request_id"] == identity
    return "reported"


@pytest.mark.asyncio
async def test_codex_file_change_checks_every_path_and_fails_closed(tmp_path: Path) -> None:
    work = tmp_path / "work"
    work.mkdir()
    inside = str(work / "a.py")

    def one(**fields: Any) -> list[dict[str, Any]]:
        return [{"path": inside, "kind": {"type": "update"}, "diff": "", **fields}]

    def move(source: str, target: Any) -> list[dict[str, Any]]:
        return [{"path": source, "kind": {"type": "update", "move_path": target}, "diff": ""}]

    # (item id, changes, grantRoot or ..., expected outcome)
    legal: list[tuple[Any, Any, Any, str]] = [
        ("update-no-move", one(), ..., "connector:accept"),
        ("update-null-move", move(inside, None), ..., "connector:accept"),
        ("move-in", move(inside, str(work / "b.py")), ..., "connector:accept"),
        ("add", one(kind={"type": "add"}), ..., "connector:accept"),
        ("delete", one(kind={"type": "delete"}), ..., "connector:accept"),
        ("relative-in", one(path="b.py", kind={"type": "add"}), ..., "connector:accept"),
        ("root-null", one(), None, "connector:accept"),
        ("root-inside", one(), str(work / "sub"), "connector:accept"),
    ]
    malformed: list[tuple[Any, Any, Any, str]] = [
        ("target-out", move(inside, str(tmp_path / "out.py")), ..., "reported"),
        ("target-dots", move("a.py", "../escape.py"), ..., "reported"),
        ("source-out", move(str(tmp_path / "out.py"), inside), ..., "reported"),
        ("second-target-out", one() + move(str(work / "e.py"), "/etc/x"), ..., "reported"),
        ("empty-path", one(path=""), ..., "reported"),
        ("number-path", one(path=5), ..., "reported"),
        ("null-path", one(path=None), ..., "reported"),
        ("no-path", [{"kind": {"type": "add"}, "diff": ""}], ..., "reported"),
        ("no-kind", [{"path": inside, "diff": ""}], ..., "reported"),
        ("string-kind", one(kind="add"), ..., "reported"),
        ("null-kind", one(kind=None), ..., "reported"),
        ("kind-without-type", one(kind={}), ..., "reported"),
        ("unknown-type", one(kind={"type": "rename"}), ..., "reported"),
        ("type-list", one(kind={"type": ["update"]}), ..., "reported"),
        ("type-object", one(kind={"type": {"add": True}}), ..., "reported"),
        ("empty-move", move(inside, ""), ..., "reported"),
        ("number-move", move(inside, 5), ..., "reported"),
        ("add-with-move", one(kind={"type": "add", "move_path": inside}), ..., "reported"),
        ("delete-with-move", one(kind={"type": "delete", "move_path": inside}), ..., "reported"),
        ("empty-changes", [], ..., "reported"),
        ("object-changes", {"path": inside}, ..., "reported"),
        ("string-changes", inside, ..., "reported"),
        ("null-changes", None, ..., "reported"),
        ("string-change", [inside], ..., "reported"),
        ("null-change", [None], ..., "reported"),
        ("root-outside", one(), str(tmp_path), "reported"),
        ("unknown-home-path", one(path=UNKNOWN_HOME), ..., "reported"),
        ("unknown-home-move", move(inside, UNKNOWN_HOME), ..., "reported"),
        ("unknown-home-root", one(), UNKNOWN_HOME, "reported"),
        ("nul-path", one(path=f"{inside}\x00x"), ..., "reported"),
        ("nul-move", move(inside, f"{inside}\x00"), ..., "reported"),
        ("nul-root", one(), f"{work}\x00", "reported"),
    ]
    # Each malformed case is followed by a legal one the connector must still answer.
    cases = legal + [
        case
        for bad in malformed
        for case in (bad, (f"after-{bad[0]}", one(), ..., "connector:accept"))
    ]
    owner = codex.AppServer(cwd=str(work))
    async with serve(owner.handler, "127.0.0.1", 0) as listener:
        driver, events = await codex.connected(owner, listener, tmp_path)
        try:
            await driver.execute(
                codex.command("prompt", "scoped", prompt="fix", scope={"write_paths": [str(work)]})
            )
            await codex.until(events, lambda kind, value: value["operation_id"] == "scoped")
            outcomes = {}
            for identity, (item, changes, root, _expected) in enumerate(cases, start=1):
                label = str(item)
                params = started_item(item, changes)
                if (item, changes, root, _expected) in legal:
                    valid("ItemStartedNotification", params)
                await owner.notify("item/started", params)
                approval: dict[str, Any] = {
                    "itemId": label,
                    "startedAtMs": int(time.time() * 1000),
                }
                if root is not ...:
                    approval["grantRoot"] = root
                if isinstance(root, str | None) and isinstance(item, str):
                    valid(
                        "FileChangeRequestApprovalParams",
                        {"threadId": "thread", "turnId": "turn-1", **approval},
                    )
                await owner.request(
                    identity, "item/fileChange/requestApproval", "turn-1", **approval
                )
                outcomes[label] = await outcome(owner, events, identity)
            assert outcomes == {str(case[0]): case[3] for case in cases}
        finally:
            await driver.stop()
