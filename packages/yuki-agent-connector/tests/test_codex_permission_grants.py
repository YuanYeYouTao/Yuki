GRANT = {"network": {"enabled": True}}
DENIAL = {"permissions": {}, "scope": "turn"}
TURN = {"permissions": GRANT, "scope": "turn"}
STRICT = {**TURN, "strictAutoReview": True}
ENTRY = {"access": "write", "path": {"type": "path", "path": "/work/x"}}
UINT_MAX = 2**64 - 1


def depth(value: Any) -> dict[str, Any]:
    return {"response": {"permissions": {"fileSystem": {"globScanMaxDepth": value}}}}


def granted(permissions: dict[str, Any], **extra: Any) -> dict[str, Any]:
    return {"permissions": permissions, **extra, "scope": "turn"}


