@pytest.mark.asyncio
async def test_codex_permission_grants_are_turn_only_and_schema_valid(tmp_path: Path) -> None:
    owner = codex.AppServer()
    async with serve(owner.handler, "127.0.0.1", 0) as listener:
        driver, events = await codex.connected(owner, listener, tmp_path)
        try:
            await driver.execute(codex.command("prompt", "yuki", prompt="fix"))
            await codex.until(events, lambda kind, value: value["operation_id"] == "yuki")

            async def answer(identity: int, given: dict[str, Any]) -> Any:
                try:
                    await driver.execute(
                        codex.command(
                            "respond",
                            f"answer-{identity}-{len(owner.calls)}",
                            execution="turn-1",
                            operation_id="yuki",
                            permission_id=str(identity),
                            connection_id=driver.rpc.connection_id,
                            **given,
                        )
                    )
                except DriverError as error:
                    await asyncio.sleep(0.05)
                    assert owner.answers.empty()
                    return error.code
                except Exception as error:  # not a refusal
                    return type(error).__name__
                reply = await asyncio.wait_for(owner.answers.get(), 3)
                assert reply["id"] == identity
                return reply["result"]

            outcomes = {}
            for identity, (label, given, _expected) in enumerate(ANSWERS, start=1):
                params = {
                    "itemId": f"perm-{identity}",
                    "cwd": owner.cwd,
                    "startedAtMs": int(time.time() * 1000),
                    "permissions": GRANT,
                    "reason": "needs network",
                }
                valid(
                    "PermissionsRequestApprovalParams",
                    {"threadId": "thread", "turnId": "turn-1", **params},
                )
                await owner.request(
                    identity, "item/permissions/requestApproval", "turn-1", **params
                )
                await codex.until(events, lambda kind, value: kind == "permission")
                outcomes[label] = await answer(identity, given)
            assert outcomes == {label: expected for label, _given, expected in ANSWERS}
            for result in outcomes.values():
                if isinstance(result, dict):
                    valid("PermissionsRequestApprovalResponse", result)
            # A refused answer leaves the request pending: the owner can still answer it.
            assert await answer(1, {"response": TURN}) == TURN
            # A decision object on a command approval is a refusal, not a crash.
            await owner.request(
                999, "item/commandExecution/requestApproval", "turn-1", command="ls"
            )
            await codex.until(events, lambda kind, value: kind == "permission")
            command = {"response": {"decision": {"acceptWithExecpolicyAmendment": {}}}}
            assert await answer(999, command) == "one_time_only"
        finally:
            await driver.stop()
