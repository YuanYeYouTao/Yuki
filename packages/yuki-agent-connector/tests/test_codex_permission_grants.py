"""Owner answers to Codex ``item/permissions/requestApproval`` grant this turn only (0.9.6).

Failure cases written before the implementation:
- G1: an answer with ``scope: "session"`` reaches Codex (the grant would outlive Yuki's
  turn into the user's own); so does an invalid scope (``null``, ``"TURN"``, a number, a
  list, an object);
- G2: an answer without ``scope`` is sent relying on Codex's default instead of an
  explicit ``"turn"``;
- G3: an accept-shaped answer (``option_id``/``decision`` ``accept``,
  ``acceptForSession``), a ``decision`` object, or one whose ``permissions`` or
  ``strictAutoReview`` the real schema rejects reaches Codex (which decodes it as an
  empty grant and resolves the request, so the owner's answer is lost), or raises
  something other than a refusal; so does an integer Codex's serde cannot decode
  (``1.0``, or beyond the 64-bit ``uint`` range);
- G4: a refused answer consumes the request, so a valid answer can no longer be given;
- G5: a decline/cancel answer is sent as ``{"decision": ...}`` (not the native schema)
  instead of an empty turn grant;
- G6: a valid turn grant is altered or refused (with or without ``strictAutoReview``,
  legacy ``read``/``write``, ``entries``, null members, the 64-bit maximum, or fields
  the schema leaves open);
- G7: a ``decision`` object on a command approval raises instead of ``one_time_only``.

Answers are validated against the schema generated by ``codex app-server
generate-json-schema`` from codex-cli 0.169.0 (``fakes/codex_schema``). Codex's own
app-server decodes an undecodable permissions response as an empty grant with
``scope: turn``; the connector does not lean on that.
"""

